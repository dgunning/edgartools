"""edgar_read ``earnings`` returned a placeholder instead of the release's statements.

On ``CurrentReport``, ``income_statement``, ``balance_sheet`` and ``cash_flow_statement``
are properties returning a ``FinancialTable``. The reader called them, so each call
raised ``TypeError: 'FinancialTable' object is not callable``, which ``except
Exception: pass`` hid, leaving only the text "Earnings data available".

The section now renders the three statements (a share of the 6,000-character cap
each) and names a missing statement as missing.

Ground truth: Apple 8-K 0000320193-25-000007 (filed 2025-01-30), Exhibit 99.1,
USD millions, quarter ended December 28, 2024: total net sales 124,300, total cost
of sales 66,025, operating income 42,832, net income 36,330; total assets 344,085;
cash generated by operating activities 29,935.

GitHub Issue: https://github.com/dgunning/edgartools/issues/1720
"""
import pytest

from edgar.ai.mcp.tools import reader
from edgar.ai.mcp.tools.reader import edgar_read
from tests._offline_filings import offline_filing

APPLE_8K = "0000320193-25-000007"


@pytest.mark.vcr
async def test_issue_1720_apple_earnings_statements(monkeypatch):
    monkeypatch.setattr(reader, "find", lambda search_id: offline_filing(search_id))
    response = await edgar_read(accession_number=APPLE_8K, sections=["earnings"])
    text = response.data["sections"]["earnings"]

    assert response.success is True
    assert text != "Earnings data available"
    assert "=== Income Statement ===" in text
    assert "=== Balance Sheet ===" in text
    assert "=== Cash Flow ===" in text
    assert "Total net sales (1) | 124,300 | 119,575" in text
    assert "Total cost of sales | 66,025 | 64,720" in text
    assert "Operating income | 42,832 | 40,373" in text
    assert "Net income | 36,330 | 33,916" in text
    assert "Total assets | 344,085 | 364,980" in text
    assert "Cash generated by operating activities | 29,935 | 39,895" in text
    # No statement was cut off by the section cap
    assert "(truncated)" not in text.split("=== Cash Flow ===")[0]


@pytest.mark.fast
async def test_missing_statement_is_named_as_missing(monkeypatch):
    class Report:
        has_earnings = True
        income_statement = None
        balance_sheet = None
        cash_flow_statement = None

    class Filing:
        accession_number = "0000000000-00-000000"
        filing_date = "2024-01-01"
        company = "Test Co"
        cik = 1
        form = "8-K"

        def obj(self):
            return Report()

    monkeypatch.setattr(reader, "find", lambda search_id: Filing())
    response = await edgar_read(accession_number="0000000000-00-000000", sections=["earnings"])
    text = response.data["sections"]["earnings"]
    assert text.count("Not found in this earnings release.") == 3
