"""A derived cash-flow quarter kept the cumulative date range in its header.

GitHub Issue: https://github.com/dgunning/edgartools/issues/1697

With ``use_optimal_periods=False`` each stitched period keeps the filing's own label,
such as "Nine Months: September 28, 2025 to June 27, 2026". ``discrete_quarters=True``
replaces the nine-month value with the quarter derived from it, but
``StatementStitcher._subtract_periods`` only prefixed that label with "Q3", so the
quarter's amount sat under the nine-month range and that string became the DataFrame
column. The label now names the quarter's own dates: the day after the shorter
cumulative period ends, to the longer period's end.

Ground truth:
* Apple 10-K FY2023, accession 0000320193-23-000106 (fixture
  tests/fixtures/xbrl/aapl/10k_2023): cash generated by operating activities of
  $110,543 million for 2022-09-25 to 2023-09-30. Apple 10-Q, accession
  0000320193-23-000077 (fixture tests/fixtures/xbrl/aapl/10q_2023): $88,945 million
  for 2022-09-25 to 2023-07-01. Q4 = $21,598 million, July 2 to September 30, 2023.
* Apple 10-Qs 0000320193-26-000020 ($116,996 million, nine months ended 2026-06-27)
  and 0000320193-26-000013 ($82,627 million, six months ended 2026-03-28): Q3 =
  $34,369 million, March 29 to June 27, 2026.
"""
import pytest

from edgar.xbrl import XBRL, XBRLS

OPERATING = "us-gaap_NetCashProvidedByUsedInOperatingActivities"


def _operating_row(xbrls):
    statement = xbrls.statements.cash_flow_statement(
        max_periods=8, standard=False, use_optimal_periods=False, discrete_quarters=True)
    frame = statement.to_dataframe()
    return frame[frame.concept == OPERATING].iloc[0]


@pytest.mark.fast
def test_derived_q4_is_headed_by_its_own_dates():
    xbrls = XBRLS.from_xbrl_objects([
        XBRL.from_directory("tests/fixtures/xbrl/aapl/10k_2023"),
        XBRL.from_directory("tests/fixtures/xbrl/aapl/10q_2023"),
    ])
    row = _operating_row(xbrls)
    assert row["Q4 Quarterly: July 02, 2023 to September 30, 2023"] == 21_598_000_000
    assert not any("Q4 Annual" in str(column) for column in row.index)
    # The nine-month period that was not converted keeps its filed value and range
    assert row["Nine Months: September 25, 2022 to July 01, 2023"] == 88_945_000_000


@pytest.mark.network
def test_apple_derived_q3_2026_is_headed_by_its_own_dates():
    from edgar import find

    xbrls = XBRLS.from_xbrl_objects([
        XBRL.from_filing(find("0000320193-26-000020")),
        XBRL.from_filing(find("0000320193-26-000013")),
    ])
    row = _operating_row(xbrls)
    assert row["Q3 Quarterly: March 29, 2026 to June 27, 2026"] == 34_369_000_000
    assert not any("Nine Months" in str(column) for column in row.index)
    assert row["Semi-Annual: September 28, 2025 to March 28, 2026"] == 82_627_000_000
