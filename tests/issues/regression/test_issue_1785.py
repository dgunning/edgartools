"""Regression: the cash-flow getters returned None for IFRS 20-F filers.

GitHub Issue: https://github.com/dgunning/edgartools/issues/1785

The operating-cash-flow concept pass knew only the two us-gaap totals, so an
IFRS filer reached it only through label patterns; Shell's "Cash flow from
operating activities" and BP's "Cash flows from (used in) operating
activities" matched none. The capex concept pass had no IFRS purchase line, and
TSMC captions its row just "Property, plant and equipment". Free cash flow
followed both to None.

Capex is the investing line for cash paid for PP&E: for Shell, its "Capital
expenditure" line (18,947 $M), not its broader "Cash capital expenditure"
subtotal (20,915), which adds investments in joint ventures and securities.
"""
import pandas as pd
import pytest

from edgar.financials import Financials

OCF = 'ifrs-full_CashFlowsFromUsedInOperatingActivities'


def _stub(rows):
    df = pd.DataFrame(
        [{'concept': c, 'label': lbl, 'abstract': False, '2025-12-31': v} for c, lbl, v in rows])
    financials = Financials(object())
    financials._render_statement_frame = lambda statement_type: (None, df.copy())
    return financials


@pytest.mark.fast
def test_shell_shape_uses_the_capital_expenditure_line_not_the_subtotal():
    financials = _stub([
        (OCF, 'Cash flow from operating activities', 42863000000),
        ('shel_CashOutflowForTotalCashCapitalExpenditure', 'Cash capital expenditure', 20915000000),
        ('ifrs-full_PurchaseOfOtherLongtermAssetsClassifiedAsInvestingActivities', 'Capital expenditure', 18947000000),
    ])
    assert financials.get_operating_cash_flow() == 42863000000
    assert financials.get_capital_expenditures() == 18947000000
    assert financials.get_free_cash_flow() == 23916000000


@pytest.mark.fast
def test_ifrs_purchase_concepts_resolve_whatever_the_caption():
    """Rows and values read from TSMC 20-F FY2025, 0001628280-26-025362 (NT$
    thousands), and BP 20-F FY2025, 0000313807-26-000006 ($M). Not recorded as
    cassettes: TSMC's XBRL alone is 27 MB."""
    tsmc = _stub([
        (OCF, 'Net cash generated by operating activities', 2274975600000),
        ('ifrs-full_PurchaseOfPropertyPlantAndEquipmentClassifiedAsInvestingActivities',
         'Property, plant and equipment', 1272410500000),
    ])
    assert tsmc.get_capital_expenditures() == 1272410500000
    assert tsmc.get_free_cash_flow() == 2274975600000 - 1272410500000

    bp = _stub([
        (OCF, 'Cash flows from (used in) operating activities', 24493000000),
        ('ifrs-full_PurchaseOfPropertyPlantAndEquipmentIntangibleAssetsOtherThanGoodwill'
         'InvestmentPropertyAndOtherNoncurrentAssets',
         'Expenditure on property, plant and equipment, intangible and other assets', 13221000000),
    ])
    assert bp.get_operating_cash_flow() == 24493000000
    assert bp.get_capital_expenditures() == 13221000000


@pytest.mark.fast
def test_shells_capex_concept_resolves_whatever_its_caption():
    """Shell files capital expenditure as
    ifrs-full:PurchaseOfOtherLongtermAssetsClassifiedAsInvestingActivities; the concept,
    not the exact caption "Capital expenditure", identifies it."""
    financials = _stub([
        (OCF, 'Cash flow from operating activities', 42863000000),
        ('shel_CashOutflowForTotalCashCapitalExpenditure', 'Cash capital expenditure', 20915000000),
        ('ifrs-full_PurchaseOfOtherLongtermAssetsClassifiedAsInvestingActivities', 'Capital investment', 18947000000),
    ])
    assert financials.get_capital_expenditures() == 18947000000


def _xbrl_only(**filing):
    """The filing's XBRL, read from the documents its index page lists
    (FilingSGML.from_homepage), so the cassette holds only the files parsed."""
    from edgar import Filing
    from edgar.sgml.sgml_common import FilingSGML

    filing = Filing(**filing)
    filing._sgml = FilingSGML.from_homepage(filing.homepage)
    return filing.xbrl()


@pytest.mark.network
@pytest.mark.vcr
def test_shell_reports_its_cash_flows():
    """Shell 20-F FY2025, 0001628280-26-017024, R7 ($M): Cash flow from operating
    activities 42,863 (2024: 54,687); Capital expenditure (18,947) (2024: (19,601))."""
    shell = Financials(_xbrl_only(form='20-F', filing_date='2026-03-12', company='Shell plc',
                                  cik=1306965, accession_no='0001628280-26-017024'))
    assert shell.get_operating_cash_flow() == 42863000000
    assert shell.get_operating_cash_flow(1) == 54687000000
    assert shell.get_capital_expenditures() == 18947000000
    assert shell.get_capital_expenditures(1) == 19601000000
    assert shell.get_free_cash_flow() == 23916000000

