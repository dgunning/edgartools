"""
Regression test for Issue #683: StatementNotFound error when stitching cash flow for VALE

GitHub Issue: https://github.com/dgunning/edgartools/issues/683

Bug (FIXED): stitching cash flow across VALE's 20-F filings raised
`StatementNotFound` and aborted the whole operation.

Fix: both stitching paths in `edgar/xbrl/stitching/core.py` (optimal periods and
the traditional per-filing loop) catch `StatementNotFoundError` and skip the
filing that lacks the statement, instead of crashing.

The premise first recorded here, that VALE's 20-Fs lack a cash flow role, was
wrong: all three declare "00000005 - Statement - Consolidated Statement of Cash
Flows", and the empty result came from IFRS concepts failing the essential-concept
gate (fixed separately; see test_issue_gi1n_ifrs_cashflow_resolution.py). Because
every real VALE filing has the role, stitching the real filings never reaches the
skip, so `TestStitchingSkipsAFilingWithoutTheStatement` removes the statement from
one filing with a throwaway subclass and checks that the other two still stitch.

Offline: the three 20-Fs are verbatim SEC XBRL files committed gzipped under
tests/fixtures/xbrl_gz/vale/ (accessions and checksums in its README). This test
used to stitch Company('VALE').get_filings(form='20-F').head(3), whose
period assertions would have failed as soon as VALE filed its FY2026 20-F.
XBRL.from_directory() on the fixtures gives a stitched cash flow statement equal
to the one from filing.xbrl() on the live filings, on both stitching paths
(checked 2026-11-23).

Ground truth, "Net cash generated by operating activities"
(vale_CashFlowFromUsedInOperatingActivities), as reported in each 20-F:
- FY2025, accession 0001292814-26-001844: 8,801,000,000
- FY2024, accession 0001292814-25-001137: 9,366,000,000
- FY2023, accession 0001292814-24-001463: 13,165,000,000
"""

import gzip
from pathlib import Path

import pytest

from edgar.exceptions import StatementNotFoundError
from edgar.xbrl import XBRL
from edgar.xbrl.stitching import XBRLS

pytestmark = pytest.mark.fast

FIXTURES = Path(__file__).parents[2] / "fixtures" / "xbrl_gz" / "vale"
YEARS = ["2025", "2024", "2023"]  # newest first, as Filings are ordered

OPERATING = "vale_CashFlowFromUsedInOperatingActivities"
OPERATING_CASH = {
    "duration_2025-01-01_2025-12-31": 8_801_000_000,
    "duration_2024-01-01_2024-12-31": 9_366_000_000,
    "duration_2023-01-01_2023-12-31": 13_165_000_000,
}


class _WithoutCashFlow(XBRL):
    """A filing whose cash flow statement cannot be resolved."""

    def get_statement_by_type(self, statement_type, *args, **kwargs):
        if statement_type == "CashFlowStatement":
            raise StatementNotFoundError(
                statement_type=statement_type,
                confidence=0.0,
                found_statements=[],
                entity_name="VALE S.A.",
                reason="removed for #683",
            )
        return super().get_statement_by_type(statement_type, *args, **kwargs)


@pytest.fixture(scope="module")
def vale_dirs(tmp_path_factory):
    """Decompress each 20-F's fixture files into its own temp directory."""
    dirs = {}
    for year in YEARS:
        src = FIXTURES / f"20f_{year}"
        gz_files = sorted(src.glob("*.gz"))
        assert gz_files, f"No XBRL fixture files in {src}"
        dest = tmp_path_factory.mktemp(f"vale_{year}")
        for gz in gz_files:
            (dest / gz.name[:-3]).write_bytes(gzip.decompress(gz.read_bytes()))
        dirs[year] = dest
    return dirs


@pytest.fixture(scope="module")
def vale_xbrls(vale_dirs):
    return {year: XBRL.from_directory(vale_dirs[year]) for year in YEARS}


def _operating_values(statement):
    rows = [r for r in statement["statement_data"] if r.get("concept") == OPERATING]
    assert len(rows) == 1, "the operating total did not survive stitching"
    return rows[0]["values"]


def test_every_filing_declares_the_cash_flow_role(vale_xbrls):
    """The precondition: each real 20-F has exactly one cash flow role, so the
    stitch below is three filings deep, not 'whatever survived'."""
    for year, xbrl in vale_xbrls.items():
        roles = [s for s in xbrl.get_all_statements() if s.get("type") == "CashFlowStatement"]
        assert [str(s["definition"]) for s in roles] == \
            ["00000005 - Statement - Consolidated Statement of Cash Flows"], year


def test_vale_stitched_cashflow(vale_xbrls):
    """Stitching all three 20-Fs gives one column per fiscal year and each
    year's operating total as filed."""
    xbrls = XBRLS.from_xbrl_objects([vale_xbrls[y] for y in YEARS])

    df = xbrls.statements.cash_flow_statement().to_dataframe()
    periods = [c for c in df.columns if str(c).startswith("20")]
    assert periods == ["2025-12-31", "2024-12-31", "2023-12-31"]

    statement = xbrls.get_statement("CashFlowStatement")
    assert _operating_values(statement) == OPERATING_CASH


class TestStitchingSkipsAFilingWithoutTheStatement:
    """#683 itself: a filing that raises StatementNotFoundError is skipped and
    the rest still stitch, on both stitching paths."""

    @pytest.fixture(scope="class")
    def xbrl_list(self, vale_dirs, vale_xbrls):
        stripped = _WithoutCashFlow.from_directory(vale_dirs["2024"])
        with pytest.raises(StatementNotFoundError):
            stripped.get_statement_by_type("CashFlowStatement")
        return [vale_xbrls["2025"], stripped, vale_xbrls["2023"]]

    def test_optimal_periods_drop_the_skipped_year(self, xbrl_list):
        """The optimal-periods path takes each filing's own fiscal year, so the
        skipped filing's year is absent and the other two are as filed."""
        statement = XBRLS.from_xbrl_objects(xbrl_list).get_statement("CashFlowStatement")

        assert _operating_values(statement) == {
            "duration_2025-01-01_2025-12-31": 8_801_000_000,
            "duration_2023-01-01_2023-12-31": 13_165_000_000,
        }
        assert not any("2024-01-01_2024-12-31" in key for key, _ in statement["periods"])

    def test_traditional_path_stitches_the_remaining_filings(self, xbrl_list):
        """The traditional path stitches every period each remaining filing
        reports. The FY2025 20-F carries FY2024 as its comparative year, so
        FY2024's 9,366,000,000 survives the skip, read from that filing."""
        statement = XBRLS.from_xbrl_objects(xbrl_list).get_statement(
            "CashFlowStatement", use_optimal_periods=False)

        assert _operating_values(statement) == OPERATING_CASH

    def test_the_skipped_filing_still_answers_other_statements(self, xbrl_list):
        """Skipping is per statement type: the stripped filing's balance sheet
        still stitches, so the 2024 year-end is present there."""
        statement = XBRLS.from_xbrl_objects(xbrl_list).get_statement("BalanceSheet")
        assert "instant_2024-12-31" in [key for key, _ in statement["periods"]]
